#!/usr/bin/env python3
"""Regenerate ``public.area_distances`` from an OSRM server (run by the founder, offline).

The seeded table is an ESTIMATE (great-circle x 1.3). Real road distances come
from OSRM over the free OpenStreetMap extract for Zambia, computed once and
stored; no routing service runs in production and no paid map API is called.

One-time OSRM setup on a laptop (about 1 GB of disk, ~10 minutes):

    curl -LO https://download.geofabrik.de/africa/zambia-latest.osm.pbf
    docker run -t -v "$PWD:/data" ghcr.io/project-osrm/osrm-backend \\
        osrm-extract -p /opt/car.lua /data/zambia-latest.osm.pbf
    docker run -t -v "$PWD:/data" ghcr.io/project-osrm/osrm-backend osrm-partition /data/zambia-latest.osrm
    docker run -t -v "$PWD:/data" ghcr.io/project-osrm/osrm-backend osrm-customize /data/zambia-latest.osrm
    docker run -t -p 5000:5000 -v "$PWD:/data" ghcr.io/project-osrm/osrm-backend \\
        osrm-routed --algorithm mld --max-table-size 200 /data/zambia-latest.osrm

Then (areas are read from the database; the output is a reviewable SQL file):

    python3 scripts/ops/build_area_distances.py --db-url "$DATABASE_URL" \\
        --osrm http://127.0.0.1:5000 --out area_distances.sql
    psql "$DATABASE_URL" -v ON_ERROR_STOP=1 -f area_distances.sql

``--estimate`` writes the interim great-circle x road-factor table instead
(no OSRM needed). Rows with ``manual_override = true`` are never overwritten.
Data (c) OpenStreetMap contributors, ODbL: keep the attribution in ``source``.
"""

from __future__ import annotations

import argparse
import json
import math
import subprocess
import sys
import urllib.request
from collections.abc import Sequence
from dataclasses import dataclass
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

ESTIMATE_SOURCE = "estimate: great-circle x {factor} - refresh with OSRM"
OSRM_SOURCE = "osrm {profile} (c) OpenStreetMap contributors, {stamp}"
MOTORBIKE_KMH = 25


@dataclass(frozen=True)
class AreaPoint:
    slug: str
    lat: float
    lng: float


@dataclass(frozen=True)
class Pair:
    from_area: str
    to_area: str
    road_km: Decimal
    minutes: int


def load_areas(db_url: str) -> list[AreaPoint]:
    sql = (
        "select coalesce(json_agg(json_build_object('slug', slug, 'lat', lat, 'lng', lng) "
        "order by slug), '[]') from public.areas where active"
    )
    result = subprocess.run(
        ["psql", db_url, "-X", "-At", "-v", "ON_ERROR_STOP=1", "-c", sql],
        check=True,
        capture_output=True,
        text=True,
    )
    rows = json.loads(result.stdout.strip() or "[]")
    return [AreaPoint(str(r["slug"]), float(r["lat"]), float(r["lng"])) for r in rows]


def great_circle_km(a: AreaPoint, b: AreaPoint) -> float:
    p1, p2 = math.radians(a.lat), math.radians(b.lat)
    dp, dl = math.radians(b.lat - a.lat), math.radians(b.lng - a.lng)
    h = math.sin(dp / 2) ** 2 + math.cos(p1) * math.cos(p2) * math.sin(dl / 2) ** 2
    return 2 * 6371.0 * math.asin(math.sqrt(h))


def _km(value: float) -> Decimal:
    return Decimal(str(value)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP)


def estimate_pairs(areas: Sequence[AreaPoint], factor: float) -> list[Pair]:
    pairs: list[Pair] = []
    for a in areas:
        for b in areas:
            if a.slug == b.slug:
                continue
            road = great_circle_km(a, b) * factor
            pairs.append(Pair(a.slug, b.slug, _km(road), math.ceil(road / MOTORBIKE_KMH * 60)))
    return pairs


def osrm_pairs(areas: Sequence[AreaPoint], base_url: str, profile: str) -> list[Pair]:
    """One /table call (areas x areas) for distances (m) and durations (s)."""
    coords = ";".join(f"{a.lng:.6f},{a.lat:.6f}" for a in areas)
    url = f"{base_url.rstrip('/')}/table/v1/{profile}/{coords}?annotations=distance,duration"
    with urllib.request.urlopen(url, timeout=120) as response:  # noqa: S310 - operator URL
        payload = json.loads(response.read().decode("utf-8"))
    if payload.get("code") != "Ok":
        raise RuntimeError(f"OSRM error: {payload.get('code')} {payload.get('message')}")
    distances, durations = payload["distances"], payload["durations"]
    pairs: list[Pair] = []
    for i, a in enumerate(areas):
        for j, b in enumerate(areas):
            if i == j:
                continue
            metres, seconds = distances[i][j], durations[i][j]
            if metres is None or seconds is None:
                print(f"warning: no route {a.slug} -> {b.slug}; kept existing row", file=sys.stderr)
                continue
            pairs.append(Pair(a.slug, b.slug, _km(metres / 1000), math.ceil(seconds / 60)))
    return pairs


def _quote(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def render_sql(pairs: Sequence[Pair], source: str) -> str:
    lines = [
        "-- Generated by scripts/ops/build_area_distances.py; review before applying.",
        "begin;",
        "insert into public.area_distances (from_area, to_area, road_km, minutes, source, computed_at)",
        "values",
    ]
    values = [
        f"  ({_quote(p.from_area)}, {_quote(p.to_area)}, {p.road_km}, {p.minutes}, "
        f"{_quote(source)}, timezone('utc', now()))"
        for p in pairs
    ]
    lines.append(",\n".join(values))
    lines += [
        "on conflict (from_area, to_area) do update",
        "  set road_km = excluded.road_km, minutes = excluded.minutes,",
        "      source = excluded.source, computed_at = excluded.computed_at",
        "  where not public.area_distances.manual_override;",
        "commit;",
        "",
    ]
    return "\n".join(lines)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    parser.add_argument("--db-url", required=True, help="Postgres URL to read public.areas from")
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--osrm", help="OSRM base URL, e.g. http://127.0.0.1:5000")
    mode.add_argument("--estimate", action="store_true", help="great-circle x road factor")
    parser.add_argument("--road-factor", type=float, default=1.3)
    parser.add_argument("--profile", default="driving")
    parser.add_argument("--stamp", default="", help="extract date for the source column")
    parser.add_argument("--out", type=Path, default=Path("area_distances.sql"))
    args = parser.parse_args(argv)

    areas = load_areas(args.db_url)
    if len(areas) < 2:
        print("error: fewer than two active areas", file=sys.stderr)
        return 1
    if args.estimate:
        pairs = estimate_pairs(areas, args.road_factor)
        source = ESTIMATE_SOURCE.format(factor=args.road_factor)
    else:
        pairs = osrm_pairs(areas, args.osrm, args.profile)
        source = OSRM_SOURCE.format(profile=args.profile, stamp=args.stamp or "extract date n/a")
    args.out.write_text(render_sql(pairs, source), encoding="utf-8")
    print(f"wrote {len(pairs)} pairs for {len(areas)} areas to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
